/** Ticks per box for the 5min chart, which is where the stop is placed (§18.1). */
export const size5m = (w: RenkoWeek, asset: "WIN" | "WDO"): number =>
	asset === "WIN" ? w.win[1] : w.wdo[1]

/** Initial stop in TICKS: two boxes of the 5min chart (§7). */
export const stopTicks = (w: RenkoWeek, asset: "WIN" | "WDO"): number =>
	2 * size5m(w, asset)
